#!/usr/bin/env bash
# Apply the approved Codex portion of a setup plan. Never scans or prompts.
set -euo pipefail

base="$(cd "$(dirname "$0")/.." && pwd)"
if [ -d "$base/templates" ]; then
  template="$base/templates/AGENTS.template.md"
  registry="$base/templates/codex-hooks.json"
else
  template="$base/AGENTS.md"
  registry="$base/codex-hooks.json"
fi
LANG_PROFILE_DIR="$base/lang"
source "$base/scripts/render.sh"

usage() {
  printf '%s\n' "Usage: $0 PROJECT [--lang ID[,ID]] [--source-dir DIR] [--doc create|merge|keep]" \
    '       [--agent NAME] [--refill-agent NAME] [--rule NAME] [--skill NAME] [--hook NAME] ...' >&2
  exit 2
}
[ "$#" -gt 0 ] && [ -d "$1" ] || usage
target=$(cd "$1" && pwd -P)
shift
LANGS_CSV=
PRIMARY_SRC_DIR=
doc=keep
agents=()
refill_agents=()
rules=()
skills=()
hooks=()
while [ "$#" -gt 0 ]; do
  [ "$#" -ge 2 ] || usage
  case "$1" in
    --lang) LANGS_CSV="$2" ;;
    --source-dir) PRIMARY_SRC_DIR="$2" ;;
    --doc) doc="$2" ;;
    --agent) agents+=("$2") ;;
    --refill-agent) refill_agents+=("$2") ;;
    --rule) rules+=("$2") ;;
    --skill) skills+=("$2") ;;
    --hook) hooks+=("$2") ;;
    *) usage ;;
  esac
  shift 2
done
case "$doc" in create | merge | keep) ;; *) usage ;; esac
[[ "$LANGS_CSV" =~ ^([a-z]+(,[a-z]+)*)?$ ]] || usage
[[ "$PRIMARY_SRC_DIR" =~ ^[A-Za-z0-9_./-]*$ ]] || usage
command -v jq >/dev/null 2>&1 || {
  echo 'Codex setup requires jq.' >&2
  exit 1
}
for name in "${agents[@]:-}" "${refill_agents[@]:-}" "${rules[@]:-}" "${skills[@]:-}" "${hooks[@]:-}"; do
  [ -z "$name" ] || [[ "$name" =~ ^[a-z0-9][a-z0-9-]*$ ]] || usage
done
for name in "${agents[@]:-}"; do [ -z "$name" ] || test -r "$base/agents/$name.md" || usage; done
for name in "${rules[@]:-}"; do [ -z "$name" ] || test -r "$base/rules/$name.md" || usage; done
for name in "${skills[@]:-}"; do [ -z "$name" ] || test -r "$base/skills/$name/SKILL.md" || usage; done
for name in "${hooks[@]:-}"; do [ -z "$name" ] || jq -e --arg n "$name" 'has($n)' "$registry" >/dev/null || usage; done

# Refuse symlinked output paths and stage writes beside their destinations.
check_path() {
  local path="$1"
  while [ "$path" != "$target" ]; do
    if [ -L "$path" ]; then
      printf 'Codex setup cannot write through symlink: %s\n' "$path" >&2
      exit 1
    fi
    path=$(dirname "$path")
  done
}
skip() { printf '  • %s\n' "$*"; }
ok() { printf '  ✓ %s\n' "$*"; }
work=$(mktemp -d)
lock=
trap 'rm -rf "$work"; if [ -n "$lock" ]; then rmdir "$lock"; fi' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

codex="$target/.codex"
doc_path="$target/AGENTS.md"
hooks_path="$codex/hooks.json"
hook_dir="$codex/hooks/agent-starter"
if [ -z "${agents[*]:-}${refill_agents[*]:-}${rules[*]:-}${skills[*]:-}${hooks[*]:-}" ] && [ "$doc" = keep ]; then exit 0; fi

# A project-level lock prevents parallel installers from losing hook or doc edits.
check_path "$codex"
mkdir -p "$codex"
if ! mkdir "$codex/.agent-starter-lock" 2>/dev/null; then
  printf '%s\n' 'Another Codex setup is writing this project.' >&2
  exit 1
fi
lock="$codex/.agent-starter-lock"

install_file() {
  local src="$1" dest="$2"
  check_path "$dest"
  mkdir -p "$(dirname "$dest")"
  if [ -e "$dest" ]; then
    skip "${dest#"$target"/} (exists, kept)"
  else
    cp -p "$src" "$dest"
    ok "${dest#"$target"/}"
  fi
}
replace_file() {
  local src="$1" dest="$2" tmp
  check_path "$dest"
  tmp=$(mktemp "$(dirname "$dest")/.agent-starter.XXXXXX")
  if [ -e "$dest" ]; then
    cp -p "$dest" "$tmp"
  else
    chmod 644 "$tmp"
  fi
  if ! cat "$src" >"$tmp" || ! mv -f "$tmp" "$dest"; then
    rm -f "$tmp"
    return 1
  fi
}

for name in "${agents[@]:-}"; do
  [ -n "$name" ] || continue
  src="$base/agents/$name.md"
  dest="$codex/agents/$name.toml"
  # Canonical descriptions are single-line values, optionally JSON-style quoted.
  desc=$(sed -n 's/^description: //p' "$src" | head -1)
  case "$desc" in
    \"*\") desc=$(jq -r . <<<"$desc") ;;
  esac
  awk 'NR==1 && /^---$/ {next} !body {if (/^---$/) body=1; next} {print}' "$src" >"$work/body"
  lang_fill "$work/body"
  {
    printf '# Generated by agent-starter\nname = "%s"\n' "$name"
    printf 'description = %s\n' "$(printf '%s' "$desc" | jq -Rs .)"
    printf 'developer_instructions = %s\n' "$(jq -Rs . <"$work/body")"
    case "$name" in *-reviewer | *-analyzer | *-hunter) printf 'sandbox_mode = "read-only"\n' ;; esac
  } >"$work/agent"
  install_file "$work/agent" "$dest"
done

for name in "${refill_agents[@]:-}"; do
  [ -n "$name" ] || continue
  dest="$codex/agents/$name.toml"
  check_path "$dest"
  [ -f "$dest" ] && grep -qFx '# Generated by agent-starter' "$dest" || continue
  # Only our single-line basic-string representation can be safely round-tripped.
  encoded=$(sed -n 's/^developer_instructions = //p' "$dest")
  if ! jq -ej 'select(type == "string")' <<<"$encoded" >"$work/body" 2>/dev/null; then
    skip "${dest#"$target"/} (edited TOML, kept)"
    continue
  fi
  lang_fill "$work/body"
  jq -Rs . <"$work/body" >"$work/body-json"
  awk -v body="$work/body-json" '
    /^developer_instructions = / {getline value < body; print "developer_instructions = " value; next}
    {print}
  ' "$dest" >"$work/agent"
  if ! cmp -s "$dest" "$work/agent"; then
    replace_file "$work/agent" "$dest"
    ok "re-tailored ${dest#"$target"/}"
  fi
done

for name in "${rules[@]:-}"; do
  [ -n "$name" ] || continue
  cp "$base/rules/$name.md" "$work/rule"
  printf '\n<!-- agent-starter:codex-guidance -->\n' >>"$work/rule"
  rewrite_paths "$work/rule"
  lang_fill "$work/rule"
  install_file "$work/rule" "$codex/guidance/$name.md"
done

for name in "${skills[@]:-}"; do
  [ -n "$name" ] || continue
  dest="$target/.agents/skills/$name/SKILL.md"
  check_path "$dest"
  if [ -e "$(dirname "$dest")" ]; then
    skip ".agents/skills/$name (exists, kept)"
    continue
  fi
  ag_skill_write "$base/skills/$name/SKILL.md" "$work/SKILL.md" "$name"
  install_file "$work/SKILL.md" "$dest"
done

if [ "${#hooks[@]}" -gt 0 ]; then
  check_path "$hooks_path"
  printf '{"hooks":{}}\n' >"$work/hooks-old"
  if [ -e "$hooks_path" ]; then
    jq -e 'type == "object" and ((.hooks // {}) | type == "object" and all(.[]; type == "array"))' "$hooks_path" >/dev/null
    cp "$hooks_path" "$work/hooks-old"
  fi
  if [ -f "$codex/config.toml" ] && grep -Eq '^[[:space:]]*(\[\[?[[:space:]]*["'\'']?hooks["'\'']?([[:space:]]|\.|\])|hooks[[:space:]]*[.=])' "$codex/config.toml"; then
    skip 'hooks kept in config.toml. Move inline hooks to hooks.json before adding agent-starter hooks.'
  else
    # Use the project Git root where available, with an ancestor search for standalone projects.
    command_prefix='root=$(git rev-parse --show-toplevel 2>/dev/null) || root=; if [ ! -f "$root/.codex/hooks/agent-starter/run.sh" ]; then root=$PWD; while [ "$root" != / ] && [ ! -f "$root/.codex/hooks/agent-starter/run.sh" ]; do root=$(dirname "$root"); done; fi; bash "$root/.codex/hooks/agent-starter/run.sh"'
    install_file "$base/hooks/codex/run.sh" "$hook_dir/run.sh"
    printf '%s\n' "${hooks[@]}" | sort -u >"$work/selected"
    while IFS= read -r name; do
      install_file "$base/hooks/claude/$name.sh" "$hook_dir/policies/$name.sh"
    done <"$work/selected"
    jq --slurpfile registry "$registry" --rawfile names "$work/selected" --arg prefix "$command_prefix" '
      reduce ($names | split("\n")[] | select(length > 0)) as $name (.;
        reduce $registry[0][$name][] as $spec (.;
          ($prefix + " " + $name) as $command |
          if any(.hooks[$spec.event][]?.hooks[]?; .command == $command) then .
          else .hooks[$spec.event] += [
            ({hooks: [{type:"command", command:$command, timeout:$spec.timeout}]} +
              (if $spec.matcher then {matcher:$spec.matcher} else {} end))
          ] end
        )
      )' "$work/hooks-old" >"$work/hooks-new"
    if ! cmp -s "$work/hooks-old" "$work/hooks-new"; then
      replace_file "$work/hooks-new" "$hooks_path"
      ok '.codex/hooks.json'
    fi
    if grep -qx session-start "$work/selected" && [ ! -e "$codex/.agent-starter.json" ]; then
      (cd "$target" && AGENT_STARTER_FINGERPRINT=1 bash "$hook_dir/policies/session-start.sh") >"$work/fingerprint"
      install_file "$work/fingerprint" "$codex/.agent-starter.json"
    fi
    ok 'Review the new project hooks with /hooks in Codex.'
  fi
fi

if [ "$doc" = create ] || [ "$doc" = merge ]; then
  check_path "$doc_path"
  if [ ! -e "$doc_path" ]; then
    cp "$template" "$work/doc"
    lang_fill "$work/doc"
  elif [ "$doc" = merge ]; then
    cp "$doc_path" "$work/doc"
  fi
  if [ -f "$work/doc" ]; then
    if [ -d "$codex/guidance" ] && ! grep -qF '## Codex project guidance' "$work/doc"; then
      printf '\n## Codex project guidance\n\nRead the relevant files under `.codex/guidance/` before editing. Each file describes the area it covers and may list matching paths.\n' >>"$work/doc"
    fi
    if [ ! -e "$doc_path" ] || ! cmp -s "$work/doc" "$doc_path"; then
      replace_file "$work/doc" "$doc_path"
      ok 'AGENTS.md'
    fi
  fi
fi
if [ -d "$codex/guidance" ] && { [ ! -f "$doc_path" ] || ! grep -qF '.codex/guidance/' "$doc_path"; }; then
  skip 'Reference .codex/guidance/ from AGENTS.md to make the selected guidance discoverable.'
fi
if [ -f "$target/AGENTS.override.md" ]; then
  skip 'AGENTS.override.md takes precedence over AGENTS.md in Codex.'
fi
